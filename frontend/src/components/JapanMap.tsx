export default function JapanMap({ prefectures, onPrefectureClick }: JapanMapProps) {
  const prefectureMap = new Map(prefectures.map(p => [p.id, p]));

  return (
    <div className="map-container">
      <svg viewBox="0 0 620 1600" preserveAspectRatio="xMidYMid meet">
        {/* 海の背景 */}
        <defs>
          <linearGradient id="seaGradient" x1="0%" y1="0%" x2="0%" y2="100%">
            <stop offset="0%" stopColor="#e8f4fc" />
            <stop offset="100%" stopColor="#d0e8f5" />
          </linearGradient>
        </defs>
        <rect x="0" y="0" width="620" height="1600" fill="url(#seaGradient)" />

        {/* 都道府県 */}
        {Object.entries(PREFECTURE_PATHS).map(([id, path]) => {
          const pref = prefectureMap.get(Number(id));
          const visitCount = pref?.visit_count || 0;

          return (
            <g key={id} onClick={() => pref && onPrefectureClick(pref)} style={{ cursor: 'pointer' }}>
              <path
                d={path}
                fill={getColor(visitCount)}
                stroke="#fff"
                strokeWidth="1.5"
                strokeLinejoin="round"
                className="prefecture-shape"
              />
              <title>{pref?.name} ({visitCount}回訪問)</title>
            </g>
          );
        })}
      </svg>

      <div className="legend">
        <div className="legend-item">
          <div className="legend-color" style={{ background: '#e8e8e8' }}></div>
          <span>未訪問</span>
        </div>
        <div className="legend-item">
          <div className="legend-color" style={{ background: '#b3d9f2' }}></div>
          <span>1回</span>
        </div>
        <div className="legend-item">
          <div className="legend-color" style={{ background: '#5cb3e0' }}></div>
          <span>2-3回</span>
        </div>
        <div className="legend-item">
          <div className="legend-color" style={{ background: '#1a7fc4' }}></div>
          <span>4回以上</span>
        </div>
      </div>
    </div>
  );
}
